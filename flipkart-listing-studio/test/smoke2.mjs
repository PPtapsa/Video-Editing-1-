import { createRequire } from 'node:module';
import { execSync } from 'node:child_process';
const require = createRequire(import.meta.url);
const { chromium } = require(execSync('npm root -g').toString().trim() + '/playwright');
const url = 'file://' + new URL('./harness.html', import.meta.url).pathname;
const SP = process.argv[2];
const errors = [];
const browser = await chromium.launch(process.env.HTTPS_PROXY ? { proxy: { server: process.env.HTTPS_PROXY } } : {});
const page = await (await browser.newContext({ viewport: { width: 1440, height: 1000 }, ignoreHTTPSErrors: true })).newPage();
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message + ' ' + (e.stack || '').split('\n')[1]));
page.on('console', (m) => { if (m.type() === 'error' && !/fonts\.g|net::ERR/.test(m.text())) errors.push('console: ' + m.text()); });
page.setDefaultTimeout(6000);
const step = async (n, fn) => { try { await fn(); console.log('ok', n); } catch (e) { errors.push('STEP ' + n + ': ' + e.message.split('\n').slice(0, 2).join(' | ')); } };
await page.route('https://cdn.jsdelivr.net/npm/xlsx-js-style@1.2.0/dist/xlsx.bundle.js', (r) => r.fulfill({ path: SP + '/xjs/package/dist/xlsx.bundle.js', contentType: 'application/javascript' }));
await page.goto(url); await page.waitForTimeout(600);
await step('new listing drain', async () => {
  await page.click('button:has-text("New")');
  await page.selectOption('#catSel', 'drain');
  await page.click('#tab_pd');
  await page.fill('#f_modelNumber', 'AquaLock Square 5x5');
  for (const o of ['Floor', 'Bathroom Sink', 'Basin']) { await page.click('.field[data-key="application"] .ms-box'); await page.locator('.ms-pop .ms-opt').filter({ has: page.locator('span', { hasText: new RegExp('^' + o + '$') }) }).first().click(); await page.keyboard.press('Escape'); }
  await page.click('.field[data-key="material"] .ms-box'); await page.locator('.ms-pop .ms-opt').filter({ hasText: /^Stainless Steel/ }).click(); await page.keyboard.press('Escape');
  await page.selectOption('#f_style', 'Push Down Strainer');
  await page.click('.field[data-key="withTailPiece"] button:has-text("No")');
  await page.fill('#f_meshDiameter', '12.5');
  await page.fill('#f_setOf', '1');
});
await step('images', async () => {
  await page.click('#tab_images');
  await page.setInputFiles('.img-slot >> nth=0 >> input[type=file]', SP + '/big.png');
  await page.waitForTimeout(500);
  await page.setInputFiles('.img-slot >> nth=1 >> input[type=file]', SP + '/small.png');
  await page.waitForTimeout(500);
  const meta = await page.locator('.img-meta').allTextContents();
  console.log('img meta:', JSON.stringify(meta.slice(0, 2)));
});
await page.screenshot({ path: SP + '/shots/20-images.png' });
await step('keyword upload', async () => {
  await page.click('#tab_ai');
  await page.setInputFiles('input[accept=".xlsx,.xls,.csv"]', SP + '/kw.csv');
  await page.waitForSelector('button:has-text("Analyse keywords")', { timeout: 15000 });
  await page.selectOption('select:near(:text("Search volume / metric"))', { label: 'Search Volume' }).catch(() => {});
  await page.click('button:has-text("Analyse keywords")');
  await page.waitForTimeout(300);
  console.log('kpis:', (await page.locator('.kpi').allTextContents()).join(' | '));
  await page.locator('.uncov select').first().selectOption({ index: 1 });
  await page.waitForTimeout(200);
});
await page.screenshot({ path: SP + '/shots/21-ai.png', fullPage: true });
await step('drain lab', async () => {
  await page.click('#tab_lab'); await page.waitForTimeout(300);
  await page.click('button:has-text("Build from rules")'); await page.waitForTimeout(300);
  const vers = await page.locator('.ver textarea').evaluateAll((els) => els.map((e) => e.value));
  console.log('versions:', JSON.stringify(vers));
  console.log('live title:', await page.locator('.live-title').first().textContent());
  await page.locator('.sec:has-text("Search Keywords builder") button:has-text("Select all")').click();
  await page.locator('.sec:has-text("Search Keywords builder") button:has-text("Add selected")').click();
  await page.waitForTimeout(200);
});
await page.screenshot({ path: SP + '/shots/22-drain-lab.png', fullPage: true });
await step('brand add + hsn add', async () => {
  await page.selectOption('#brandSel', '__add');
  await page.fill('.pop input >> nth=0', 'Aquant');
  await page.fill('.pop input >> nth=1', 'AQ');
  await page.click('.pop button:has-text("Add")');
  await page.click('#tab_price');
  await page.click('.field[data-key="hsn"] button:has-text("Add HSN")');
  await page.fill('.pop input >> nth=0', '84818020');
  await page.fill('.pop input >> nth=1', 'Taps, cocks of brass');
  await page.click('.pop button:has-text("Add")');
  await page.waitForTimeout(200);
  console.log('hsn value:', await page.inputValue('#f_hsn'));
});
await step('warranty', async () => {
  await page.selectOption('#catSel', 'faucet');
  await page.click('#tab_lab'); await page.waitForTimeout(200);
  await page.click('.seg button:has-text("5 year")');
  await page.locator('.sec:has-text("Warranty builder") .fktm-add input').first().fill('Cartridge');
  await page.keyboard.press('Enter');
  await page.click('button:has-text("Write to warranty fields")');
  await page.click('#tab_ad'); await page.waitForTimeout(150);
  console.log('summary:', await page.inputValue('#f_warrantySummary'));
});
await step('saved drawer actions', async () => {
  await page.keyboard.press('Control+s'); await page.waitForTimeout(500);
  await page.click('button:has-text("Saved Listings")'); await page.waitForTimeout(200);
  const n0 = await page.locator('.saved-card').count();
  await page.locator('.saved-card >> nth=0 >> button:has-text("Duplicate")').click(); await page.waitForTimeout(500);
  const n1 = await page.locator('.saved-card').count();
  await page.locator('.saved-card >> nth=0 >> button:has-text("Rename")').click();
  await page.fill('.saved-card form input', 'Renamed listing');
  await page.click('.saved-card form button:has-text("Rename")'); await page.waitForTimeout(400);
  const names = await page.locator('.saved-card .nm').allTextContents();
  console.log('cards', n0, '->', n1, JSON.stringify(names));
  await page.locator('.saved-card:not(.cur) >> nth=0 >> button:has-text("Delete")').click();
  await page.click('.pop button:has-text("Delete")'); await page.waitForTimeout(400);
  console.log('after delete', await page.locator('.saved-card').count());
});
await page.screenshot({ path: SP + '/shots/23-saved.png' });
await step('category builder new', async () => {
  await page.keyboard.press('Escape');
  await page.selectOption('#catSel', '__add'); await page.waitForTimeout(200);
  await page.fill('.cb input >> nth=0', 'Grab Bar');
  await page.click('button:has-text("Save category")'); await page.waitForTimeout(300);
  console.log('cat now:', await page.inputValue('#catSel'));
  await page.click('#tab_pd'); await page.click('#tab_lab'); await page.click('#tab_variants'); await page.waitForTimeout(150);
});
console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'NO ERRORS');
await browser.close();
